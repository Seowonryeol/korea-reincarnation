export function getTotalWeight(regions = REGIONS_DATA, mode = 'birth') {
  if (mode === 'population') {
    return regions.reduce((acc, r) => acc + r.population, 0);
  }
  return regions.reduce((acc, r) => acc + r.annualBirths, 0);
}
